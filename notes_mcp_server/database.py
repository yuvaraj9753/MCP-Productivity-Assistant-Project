import os
from pathlib import Path
from typing import Any

from dotenv import load_dotenv
from sqlalchemy import create_engine, text
from sqlalchemy.engine import Engine, RowMapping


PROJECT_ROOT = Path(__file__).resolve().parent.parent
load_dotenv(PROJECT_ROOT / ".env")

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise ValueError(
        "DATABASE_URL not found. Set it in your .env file "
        "or deployment environment variables."
    )

# Normalize common PostgreSQL URL formats for psycopg.
if DATABASE_URL.startswith("postgres://"):
    DATABASE_URL = DATABASE_URL.replace(
        "postgres://",
        "postgresql+psycopg://",
        1,
    )
elif DATABASE_URL.startswith("postgresql://"):
    DATABASE_URL = DATABASE_URL.replace(
        "postgresql://",
        "postgresql+psycopg://",
        1,
    )

engine: Engine = create_engine(
    DATABASE_URL,
    pool_pre_ping=True,
    pool_recycle=300,
    connect_args={"connect_timeout": 10},
)


def get_connection():
    """Create a SQLAlchemy database connection."""
    return engine.connect()


def initialize_database() -> None:
    """Create the notes table if it does not exist."""

    with engine.begin() as connection:
        connection.execute(
            text(
                """
                CREATE TABLE IF NOT EXISTS notes (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title TEXT NOT NULL,
                    content TEXT NOT NULL,
                    tags TEXT NOT NULL DEFAULT '',
                    created_at TEXT NOT NULL DEFAULT
                        to_char(
                            CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
                            'YYYY-MM-DD"T"HH24:MI:SS"Z"'
                        ),
                    updated_at TEXT NOT NULL DEFAULT
                        to_char(
                            CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
                            'YYYY-MM-DD"T"HH24:MI:SS"Z"'
                        )
                )
                """
            )
        )


def row_to_dict(
    row: RowMapping | dict[str, Any] | None,
) -> dict[str, Any] | None:
    """Convert a database row to a dictionary."""

    if row is None:
        return None

    return dict(row)


def save_note(
    title: str,
    content: str,
    tags: str = "",
) -> dict[str, Any]:
    """Save a new note."""

    title = title.strip()
    content = content.strip()

    if not title:
        raise ValueError("Note title cannot be empty.")

    if not content:
        raise ValueError("Note content cannot be empty.")

    with engine.begin() as connection:
        row = connection.execute(
            text(
                """
                INSERT INTO notes (title, content, tags)
                VALUES (:title, :content, :tags)
                RETURNING *
                """
            ),
            {
                "title": title,
                "content": content,
                "tags": tags.strip(),
            },
        ).mappings().one()

        return dict(row)


def list_notes() -> list[dict[str, Any]]:
    """Return all saved notes."""

    with engine.connect() as connection:
        rows = connection.execute(
            text("SELECT * FROM notes ORDER BY id DESC")
        ).mappings().all()

        return [dict(row) for row in rows]


def get_note(note_id: int) -> dict[str, Any] | None:
    """Retrieve a note by ID."""

    with engine.connect() as connection:
        row = connection.execute(
            text("SELECT * FROM notes WHERE id = :note_id"),
            {"note_id": note_id},
        ).mappings().first()

        return row_to_dict(row)


def search_notes(query: str) -> list[dict[str, Any]]:
    """Search notes by title, content, or tags."""

    query = query.strip()

    if not query:
        raise ValueError("Search query cannot be empty.")

    search_pattern = f"%{query}%"

    with engine.connect() as connection:
        rows = connection.execute(
            text(
                """
                SELECT *
                FROM notes
                WHERE title ILIKE :pattern
                   OR content ILIKE :pattern
                   OR tags ILIKE :pattern
                ORDER BY id DESC
                """
            ),
            {"pattern": search_pattern},
        ).mappings().all()

        return [dict(row) for row in rows]


def update_note(
    note_id: int,
    title: str | None = None,
    content: str | None = None,
    tags: str | None = None,
) -> dict[str, Any] | None:
    """Update the supplied fields of a note."""

    existing = get_note(note_id)

    if existing is None:
        return None

    updates: dict[str, str] = {}

    if title is not None:
        title = title.strip()
        if not title:
            raise ValueError("Note title cannot be empty.")
        updates["title"] = title

    if content is not None:
        content = content.strip()
        if not content:
            raise ValueError("Note content cannot be empty.")
        updates["content"] = content

    if tags is not None:
        updates["tags"] = tags.strip()

    if not updates:
        return existing

    # Column names come only from this fixed allowlist.
    allowed_columns = {"title", "content", "tags"}
    if not updates.keys() <= allowed_columns:
        raise ValueError("Invalid update field.")

    assignments = ", ".join(
        f"{column} = :{column}" for column in updates
    )

    parameters: dict[str, Any] = {
        **updates,
        "note_id": note_id,
    }

    with engine.begin() as connection:
        connection.execute(
            text(
                f"""
                UPDATE notes
                SET {assignments},
                    updated_at = to_char(
                        CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
                        'YYYY-MM-DD"T"HH24:MI:SS"Z"'
                    )
                WHERE id = :note_id
                """
            ),
            parameters,
        )

    return get_note(note_id)


def delete_note(note_id: int) -> bool:
    """Delete a note by ID."""

    with engine.begin() as connection:
        result = connection.execute(
            text("DELETE FROM notes WHERE id = :note_id"),
            {"note_id": note_id},
        )

        return result.rowcount > 0


initialize_database()