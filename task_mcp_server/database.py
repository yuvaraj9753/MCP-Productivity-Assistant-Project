import os
from pathlib import Path
from typing import Any

from dotenv import load_dotenv
from sqlalchemy import create_engine, text
from sqlalchemy.engine import Engine, RowMapping


PROJECT_ROOT = Path(__file__).resolve().parent.parent
load_dotenv(PROJECT_ROOT / ".env")

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise ValueError("DATABASE_URL not found in .env or environment.")

# Support standard PostgreSQL URLs from Supabase.
if DATABASE_URL.startswith("postgres://"):
    DATABASE_URL = DATABASE_URL.replace(
        "postgres://", "postgresql+psycopg://", 1
    )
elif DATABASE_URL.startswith("postgresql://"):
    DATABASE_URL = DATABASE_URL.replace(
        "postgresql://", "postgresql+psycopg://", 1
    )

engine: Engine = create_engine(
    DATABASE_URL,
    pool_pre_ping=True,
    pool_recycle=300,
    connect_args={"connect_timeout": 10},
)


def get_connection():
    """Return a SQLAlchemy database connection."""
    return engine.connect()


def row_to_dict(row: RowMapping | None) -> dict[str, Any] | None:
    """Convert a database row to a dictionary."""
    if row is None:
        return None

    return dict(row)


def initialize_database() -> None:
    """Create the tasks table if it does not exist."""
    with engine.begin() as connection:
        connection.execute(
            text(
                """
                CREATE TABLE IF NOT EXISTS tasks (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY
                        PRIMARY KEY,
                    title TEXT NOT NULL,
                    description TEXT NOT NULL DEFAULT '',
                    due_date TEXT,
                    priority TEXT NOT NULL DEFAULT 'medium'
                        CHECK (priority IN ('low', 'medium', 'high')),
                    status TEXT NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'completed')),
                    created_at TEXT NOT NULL DEFAULT
                        to_char(
                            CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
                            'YYYY-MM-DD"T"HH24:MI:SS"Z"'
                        ),
                    updated_at TEXT NOT NULL DEFAULT
                        to_char(
                            CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
                            'YYYY-MM-DD"T"HH24:MI:SS"Z"'
                        )
                )
                """
            )
        )


def create_task(
    title: str,
    description: str = "",
    due_date: str | None = None,
    priority: str = "medium",
) -> dict[str, Any]:
    """Create a task and return the inserted record."""

    title = title.strip()
    priority = priority.lower()

    if not title:
        raise ValueError("Task title cannot be empty.")

    if priority not in {"low", "medium", "high"}:
        raise ValueError("Priority must be low, medium, or high.")

    with engine.begin() as connection:
        row = connection.execute(
            text(
                """
                INSERT INTO tasks (title, description, due_date, priority)
                VALUES (:title, :description, :due_date, :priority)
                RETURNING *
                """
            ),
            {
                "title": title,
                "description": description.strip(),
                "due_date": due_date,
                "priority": priority,
            },
        ).mappings().one()

        return dict(row)


def list_tasks(
    status: str = "all",
    priority: str = "all",
) -> list[dict[str, Any]]:
    """List tasks with optional status and priority filters."""

    if status not in {"all", "pending", "completed"}:
        raise ValueError("Invalid task status.")

    if priority not in {"all", "low", "medium", "high"}:
        raise ValueError("Invalid task priority.")

    query = "SELECT * FROM tasks WHERE 1=1"
    parameters: dict[str, str] = {}

    if status != "all":
        query += " AND status = :status"
        parameters["status"] = status

    if priority != "all":
        query += " AND priority = :priority"
        parameters["priority"] = priority

    query += " ORDER BY id DESC"

    with engine.connect() as connection:
        rows = connection.execute(
            text(query), parameters
        ).mappings().all()

        return [dict(row) for row in rows]


def get_task(task_id: int) -> dict[str, Any] | None:
    """Get a task by its ID."""

    with engine.connect() as connection:
        row = connection.execute(
            text("SELECT * FROM tasks WHERE id = :task_id"),
            {"task_id": task_id},
        ).mappings().first()

        return row_to_dict(row)


def update_task(
    task_id: int,
    title: str | None = None,
    description: str | None = None,
    due_date: str | None = None,
    priority: str | None = None,
) -> dict[str, Any] | None:
    """Update provided task fields."""

    existing = get_task(task_id)

    if existing is None:
        return None

    updates: dict[str, Any] = {}

    if title is not None:
        title = title.strip()
        if not title:
            raise ValueError("Task title cannot be empty.")
        updates["title"] = title

    if description is not None:
        updates["description"] = description.strip()

    if due_date is not None:
        updates["due_date"] = due_date

    if priority is not None:
        priority = priority.lower()
        if priority not in {"low", "medium", "high"}:
            raise ValueError("Invalid task priority.")
        updates["priority"] = priority

    if not updates:
        return existing

    # Column names come only from the fixed dictionary above.
    assignments = ", ".join(
        f"{column} = :{column}" for column in updates
    )

    query = text(
        f"""
        UPDATE tasks
        SET {assignments},
            updated_at = to_char(
                CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
                'YYYY-MM-DD"T"HH24:MI:SS"Z"'
            )
        WHERE id = :task_id
        """
    )

    parameters = {**updates, "task_id": task_id}

    with engine.begin() as connection:
        connection.execute(query, parameters)

    return get_task(task_id)


def complete_task(task_id: int) -> dict[str, Any] | None:
    """Mark a task as completed."""

    with engine.begin() as connection:
        connection.execute(
            text(
                """
                UPDATE tasks
                SET status = 'completed',
                    updated_at = to_char(
                        CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
                        'YYYY-MM-DD"T"HH24:MI:SS"Z"'
                    )
                WHERE id = :task_id
                """
            ),
            {"task_id": task_id},
        )

    return get_task(task_id)


def delete_task(task_id: int) -> bool:
    """Delete a task by its ID."""

    with engine.begin() as connection:
        result = connection.execute(
            text("DELETE FROM tasks WHERE id = :task_id"),
            {"task_id": task_id},
        )

        return result.rowcount > 0


def get_overdue_tasks() -> list[dict[str, Any]]:
    """Get pending tasks with deadlines before today."""

    with engine.connect() as connection:
        rows = connection.execute(
            text(
                """
                SELECT *
                FROM tasks
                WHERE status = 'pending'
                  AND due_date IS NOT NULL
                  AND due_date <> ''
                  AND due_date::date < CURRENT_DATE
                ORDER BY due_date ASC
                """
            )
        ).mappings().all()

        return [dict(row) for row in rows]


def get_task_summary() -> dict[str, int]:
    """Return total, pending, and completed task counts."""

    with engine.connect() as connection:
        row = connection.execute(
            text(
                """
                SELECT
                    COUNT(*) AS total,
                    COUNT(*) FILTER (
                        WHERE status = 'pending'
                    ) AS pending,
                    COUNT(*) FILTER (
                        WHERE status = 'completed'
                    ) AS completed
                FROM tasks
                """
            )
        ).mappings().one()

        return {
            "total": row["total"],
            "pending": row["pending"],
            "completed": row["completed"],
        }


initialize_database()